<?php

declare(strict_types=1);

/**
 * The contract build (Architecture 3.3, 4.11): discovers and checks the plugin packages, writes the generated contract
 * files from them (contract/catalog: catalog, sources, layers, TERMS.md; contract/schema: catalog and layers schema;
 * contract/messages/plugins.de.json) and the PHP master data in generated/ from contract/data and contract/regions.
 *
 *   php bin/build-contract.php [path/to/contract]
 *
 * The region areas are stored as MultiPolygon coordinates, plus per country the grid for fast assignment.
 */

use CommonSight\Domain\Geo\GridTraversal;
use CommonSight\Domain\Geo\PointInPolygon;
use CommonSight\Domain\Geo\RegionGridBuilder;
use CommonSight\Infrastructure\Contract\CatalogBuilder;
use CommonSight\Infrastructure\Contract\LayerSchemaBuilder;
use CommonSight\Infrastructure\Contract\MessageCollector;
use CommonSight\Infrastructure\Contract\SourceListing;
use CommonSight\Infrastructure\Plugin\PluginDiscovery;
use CommonSight\Model\Decoded;
use CommonSight\Model\Place\BoundingBox;
use CommonSight\Model\Place\Region;
use CommonSight\Model\Value\Coordinate;
use CommonSight\Model\Value\RegionId;
use CommonSight\Model\Value\Scope;
use CommonSight\Sdk\Layer\LayerDescription;
use CommonSight\Sdk\Plugin\SourceDescription;

require dirname(__DIR__) . '/vendor/autoload.php';

const GRID_CELL_DEG = 0.05;

$contract = Decoded::of($_SERVER['argv'] ?? [])->get(1)->string() ?? dirname(__DIR__, 2) . '/contract';
$target = dirname(__DIR__) . '/generated';

$json = static fn(string $path): Decoded => Decoded::of(json_decode((string) file_get_contents($path), true, 512, JSON_THROW_ON_ERROR));

$export = static function (string $name, mixed $data) use ($target): void {
    if (!is_dir($target) && !mkdir($target, 0755, true)) {
        throw new RuntimeException('Cannot create directory: ' . $target);
    }
    $code = "<?php\n\n// Generated by bin/build-contract.php from contract/. Do not edit by hand.\n\nreturn " . var_export($data, true) . ";\n";
    file_put_contents($target . '/' . $name . '.php', $code);
    printf("  %s.php (%d KB)\n", $name, (int) (strlen($code) / 1024));
};

/** @return list<list<list<array{float, float}>>> */
$polygonsOf = static function (Decoded $geometry): array {
    $polygons = match ($geometry->get('type')->string()) {
        'Polygon' => [$geometry->get('coordinates')],
        'MultiPolygon' => $geometry->get('coordinates')->list(),
        default => throw new RuntimeException('Region area without polygon'),
    };

    return array_map(
        static fn(Decoded $rings): array => array_map(
            static fn(Decoded $ring): array => array_map(
                static fn(Decoded $p): array => [round((float) $p->get(0)->float(), 5), round((float) $p->get(1)->float(), 5)],
                $ring->list(),
            ),
            $rings->list(),
        ),
        $polygons,
    );
};

echo "Master data from $contract\n";
foreach (['countries', 'cities', 'border-places', 'border-zone'] as $name) {
    $export($name, $json($contract . '/data/' . $name . '.json')->raw());
}

// Plugins: discovered and checked once here, so that no run has to scan the folder (concept: sources as plugins, D1).
$pluginsDir = dirname(__DIR__, 2) . '/plugins';
$plugins = (new PluginDiscovery())->discover($pluginsDir);
$export('plugins', $plugins);
$sources = [];
$layers = [];
foreach ($plugins as $plugin) {
    $description = (new $plugin['factory']())->describe();
    if ($description instanceof LayerDescription) {
        $layers[] = $description;
    } elseif ($description instanceof SourceDescription) {
        $sources[] = $description;
    }
}
usort($layers, static fn(LayerDescription $a, LayerDescription $b): int => [$a->order, $a->id] <=> [$b->order, $b->id]);

/** @return array<string, array<string, mixed>> decoded file per plugin id, e.g. "catalog.json" or "messages/de.json" */
$pluginFiles = static function (string $file) use ($pluginsDir, $json): array {
    $found = [];
    foreach (glob($pluginsDir . '/*/*/' . $file) ?: [] as $path) {
        $found[basename(dirname($path, substr_count($file, '/') + 1))] = (array) $json($path)->raw();
    }

    return $found;
};

/** Writes a generated file of the contract, only when its content changed; JSON with two spaces like the hand-written files. */
$writeContract = static function (string $relative, mixed $content) use ($contract): void {
    if (!is_string($content)) {
        $encoded = json_encode($content, JSON_THROW_ON_ERROR | JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
        $content = preg_replace_callback('/^ +/m', static fn(array $m): string => str_repeat(' ', intdiv(strlen($m[0]), 2)), $encoded);
    }
    $content = rtrim((string) $content) . "\n";
    $path = $contract . '/' . $relative;
    if (@file_get_contents($path) !== $content) {
        file_put_contents($path, $content);
        printf("  contract/%s written\n", $relative);
    }
};

// Catalog terms of the core and the plugins (V14, V17) and the plugins' texts (V10).
$catalogs = new CatalogBuilder();
$catalog = $catalogs->join((array) $json($contract . '/catalog/builtin.json')->raw(), $pluginFiles('catalog.json'));
$writeContract('catalog/catalog.json', $catalog);
$writeContract('schema/catalog.schema.json', $catalogs->schema($catalog));
$writeContract('catalog/TERMS.md', $catalogs->overview($catalog));
$export('catalog', $catalog);
$namespaces = array_map(static fn(array $p): string => match ($p['kind']) {
    PluginDiscovery::LAYER => 'layer.',
    PluginDiscovery::AUTH => 'auth.',
    default => 'source.',
} . basename($p['dir']) . '.', $plugins);
$pluginTexts = (new MessageCollector())->collect((array) $json($contract . '/messages/de.json')->raw(), $pluginFiles('messages/de.json'), $namespaces);
$writeContract('messages/plugins.de.json', $pluginTexts === [] ? new stdClass() : $pluginTexts);
// Names, layers and attributions of the sources for the frontend (map credits, data use).
$writeContract('catalog/sources.json', (new SourceListing())->list($sources));
// The layer registry and the key figures per layer, from the layer plugins (concept: layers as plugins).
$registry = array_map(static fn(LayerDescription $layer): array => $layer->registryEntry(), $layers);
$writeContract('catalog/layers.json', $registry);
$export('layers', $registry);
$writeContract('schema/layers.schema.json', (new LayerSchemaBuilder())->schema($layers, $pluginFiles('schema/stats.schema.json')));

$metadata = [];
foreach ($json($contract . '/data/regions.json')->list() as $region) {
    $metadata[(string) $region->get('id')->string()] = $region;
}

// Stable official codes of the regions for plugins (concept V2); the id is the ISO 3166-2 code.
$codes = ['iso' => [], 'ags' => [], 'gkz' => [], 'bfs' => []];
$names = [];
foreach ($metadata as $id => $region) {
    $codes['iso'][$id] = $id;
    $names[$id] = (string) $region->get('name')->string();
    foreach ($region->get('codes')->entries() as $scheme => $code) {
        if (!isset($codes[$scheme])) {
            throw new RuntimeException(sprintf('Region %s: unknown code scheme %s', $id, $scheme));
        }
        $codes[$scheme][(string) $code->string()] = $id;
    }
}
$export('region-codes', ['schemes' => $codes, 'names' => $names]);

$builder = new RegionGridBuilder(new PointInPolygon(), new GridTraversal());
foreach (Scope::countries() as $country) {
    $regions = [];
    $exported = [];
    foreach ($json(sprintf('%s/regions/%s.geojson', $contract, $country->value))->get('features')->list() as $feature) {
        $id = (string) $feature->get('properties', 'id')->text();
        $meta = $metadata[$id] ?? throw new RuntimeException('Region missing in regions.json: ' . $id);
        $polygons = $polygonsOf($feature->get('geometry'));
        $bbox = array_map(static fn(Decoded $v): float => (float) $v->float(), $meta->get('bbox')->list());
        $refPoint = [(float) $meta->get('refPoint', 0)->float(), (float) $meta->get('refPoint', 1)->float()];
        $name = (string) $meta->get('name')->string();
        $aliases = $meta->get('aliases')->strings();
        $regions[] = new Region(RegionId::fromString($id), $country, $name, $aliases, new BoundingBox(...$bbox), Coordinate::fromLonLat(...$refPoint), $polygons);
        $exported[] = ['id' => $id, 'name' => $name, 'aliases' => $aliases, 'bbox' => $bbox, 'refPoint' => $refPoint, 'polygons' => $polygons];
    }
    if ($regions === []) {
        throw new RuntimeException('No regions for ' . $country->value);
    }
    $started = microtime(true);
    $grid = $builder->build($regions, GRID_CELL_DEG);
    printf("  Grid %s: %d × %d cells, %d boundary cells, %.1f s\n", $country->value, $grid->cols, $grid->rows, count($grid->candidates), microtime(true) - $started);
    $export('regions-' . $country->value, ['regions' => $exported, 'grid' => $grid->toArray()]);
}
